"""Phase 4B request flow for POST /api/ask: conversation → follow-up rewrite → retrieval → answer (or deferred)
→ conversation memory. Retrieval always completes and is returned; generation may be deferred:

  - capture / Whisper / OCR active (indexer.busy_reason, rechecked immediately before every generation) or the
    model busy beyond RAG_HEAVY_WAIT_S → the turn is stored as "queued" and generated by the background worker
    when idle; poll GET /api/ask/{request_id};
  - the queue is bounded (QUEUE_MAX): a full queue is reported (status "unavailable"), never dropped silently;
  - queued turns of a previous process are marked "expired" at startup (visible, not lost silently).
Answers are generated for the resolved standalone question; history keeps the user's original wording.
"""
from __future__ import annotations

import sys
import threading
from collections import deque

from . import answer, config, conversations, indexer, models, rag

QUEUE_MAX = 8
POLL_S = 5.0
_queue: deque[int] = deque()
_qlock = threading.Lock()
_wake = threading.Event()
_stop = threading.Event()
_thread: threading.Thread | None = None


class AskError(RuntimeError):
    pass


def _busy() -> str | None:
    try:
        return indexer.busy_reason()
    except Exception as e:  # noqa: BLE001
        return f"busy check failed: {e}"


def ask(question: str, conversation_id: str | None = None, mode: str = "hybrid", options: dict | None = None,
        generate: bool = True, llm=None, graph=None) -> dict:
    question = " ".join((question or "").split())
    if not question:
        raise AskError("question is empty")
    if mode not in rag.MODES:
        raise AskError(f"mode must be one of {rag.MODES}")
    if conversation_id and not conversations.exists(conversation_id):
        raise AskError(f"unknown conversation {conversation_id!r}")
    cid = conversation_id or conversations.create(title=question)
    turns = conversations.previous_turns(cid, 3 if conversations.DEFAULTS.get("referents") == "v2" else 2)
    rw = conversations.rewrite(question, turns, llm=llm, allow_model=generate and _busy() is None)
    exclude = list(rw["previous_cited_reels"]) if rw["exclude_previous"] else []
    if rw["scope_previous"] and rw["previous_cited_reels"]:
        keep = set(rw["previous_cited_reels"])
        exclude = [r for r in indexer.eligible() if r not in keep]
    retrieval = rag.retrieve(rw.get("retrieval_query") or rw["standalone"], mode=mode, options=options, graph=graph,
                             boost_concepts=rw["boost"], exclude_reels=exclude)
    if answer.DEFAULTS.get("passage_select"):
        from . import evidence, listing
        if not (answer.DEFAULTS.get("listing") and listing.detect(question)):
            try:          # answer-bearing passages of Reels already retrieved (Phase 4D); never fails the request
                evidence.select(retrieval["question"], retrieval)
            except Exception as e:  # noqa: BLE001
                retrieval["passage_select"] = {"error": f"{type(e).__name__}: {e}"}
    q_concepts = [{"key": c["key"], "name": c["name"]} for c in retrieval["concepts"] if c["named_in_question"]]
    tid = conversations.add_turn(
        cid, question, standalone_query=rw["standalone"],
        rewrite={**{k: rw.get(k) for k in ("method", "reason", "referents", "boost", "exclude_previous",
                                           "scope_previous", "rewrite_s", "retrieval_query", "previous_cited_reels",
                                           "clarify")},
                 "previous_term": _previous_term(turns)},
        mode_requested=mode, mode_used=retrieval["mode_used"], status="retrieved", retrieval=retrieval,
        question_concepts=q_concepts)
    if generate:
        _generate_turn(tid, rw["standalone"], retrieval, llm=llm, defer_if_busy=True)
    else:
        conversations.update_turn(tid, status="retrieval_only")
    return response(conversations.get_turn(tid))


def _previous_term(turns: list[dict]) -> str | None:
    """What 'this' refers to in a listing follow-up ("Which other Reels mention this?"): the previous deterministic
    listing's term, else the single concept the previous QUESTION named (never assistant text)."""
    if not turns:
        return None
    prev = turns[0]
    det = (prev.get("answer") or {}).get("deterministic") or {}
    if det.get("term"):
        return det["term"]
    qc = prev.get("question_concepts") or []
    return qc[0]["name"] if len(qc) == 1 else None


def _scope(rw: dict) -> dict:
    prev = rw.get("previous_cited_reels") or []
    return {"within": prev if rw.get("scope_previous") else None,
            "exclude": prev if rw.get("exclude_previous") else None, "previous_term": rw.get("previous_term")}


def clarification(names: list[str]) -> dict:
    alts = ", ".join(f"“{n}”" for n in names[:-1]) + f" or “{names[-1]}”"
    text = f"Which one do you mean: {alts}? Your previous question named more than one, so I did not want to guess."
    return {"status": "clarify", "sentences": [], "removed": [], "missing": "", "conflict": False,
            "model_said_insufficient": False, "citations": [], "text": text, "clarify": names, "generated": False,
            "gate": None, "timing": {"generate_s": 0.0, "model_load_s": 0.0, "cold": False}}


def _deterministic_turn(tid: int, retrieval: dict) -> bool:
    """Listing/count questions are answered without the model — so also while capture/processing is active —
    and an ambiguous follow-up gets a clarifying question instead of a guessed answer."""
    t = conversations.get_turn(tid) or {}
    rw = t.get("rewrite") or {}
    if rw.get("method") == "clarify" and rw.get("clarify"):
        conversations.update_turn(tid, status="clarify", answer=clarification(rw["clarify"]), cited_reels=[],
                                  cited_concepts=[])
        return True
    out = answer.deterministic(t.get("question") or "", retrieval, scope=_scope(t.get("rewrite") or {}))
    if out is None:
        return False
    conversations.update_turn(tid, status=out["status"], answer=out, retrieval=retrieval,
                              cited_reels=sorted({c["reel_id"] for c in out.get("citations", [])}), cited_concepts=[])
    return True


def _generate_turn(tid: int, standalone: str, retrieval: dict, llm=None, defer_if_busy: bool = False,
                   timeout: float | None = None) -> bool:
    """Generate one answer now. → True if generated (or failed permanently), False if it must wait.
    Capture/processing availability is rechecked immediately before generating."""
    try:
        if _deterministic_turn(tid, retrieval):
            return True
    except Exception as e:  # noqa: BLE001 — never breaks the request; normal generation follows
        print(f"[answers] deterministic listing failed: {type(e).__name__}: {e}", file=sys.stderr)
    busy = _busy()
    if busy:
        if defer_if_busy:
            _enqueue(tid, f"deferred: {busy}")
        return False
    try:
        rw = (conversations.get_turn(tid) or {}).get("rewrite") or {}
        method = rw.get("method") or "none"
        # "Which of them …" is scoped to the previous answer's Reels: context-dependent even when nothing is
        # substituted, so the hard evidence gates (computed on the question alone) must not apply (Phase 4D fix).
        follow_up = method != "none" or bool(answer.DEFAULTS.get("scoped_follow_up") and rw.get("scope_previous"))
        out = answer.respond(standalone, retrieval, llm=llm, timeout=timeout, follow_up=follow_up,
                             allow_deterministic=False)
    except models.HeavyBusy as e:
        if defer_if_busy:
            _enqueue(tid, f"deferred: {e}")
        return False
    except Exception as e:  # noqa: BLE001 — generation failure never breaks the request (retrieval is kept)
        conversations.update_turn(tid, status="error", error=f"generation failed: {type(e).__name__}: {e}")
        return True
    cited_chunks = {c["chunk_id"] for c in out.get("citations", [])}
    concepts = {c["key"]: c for chunk in sorted(cited_chunks) for c in retrieval.get("source_concepts", {}).get(chunk, [])}
    conversations.update_turn(tid, status=out["status"], answer=out, error=out.get("error"),
                              cited_reels=sorted({c["reel_id"] for c in out.get("citations", [])}),
                              cited_concepts=list(concepts.values()))
    return True


def _enqueue(tid: int, reason: str) -> None:
    with _qlock:
        if tid in _queue:
            return
        if len(_queue) >= QUEUE_MAX:
            conversations.update_turn(tid, status="unavailable",
                                      error=f"generation queue full ({QUEUE_MAX}); retrieval results are shown")
            return
        _queue.append(tid)
        conversations.update_turn(tid, status="queued", error=reason)
    _wake.set()


def queued() -> list[int]:
    with _qlock:
        return list(_queue)


def process_one(llm=None) -> int | None:
    """Generate the oldest queued answer if capture/processing are idle and the model is free.
    → the turn id handled, or None if nothing could be done now (it keeps its place in the queue)."""
    with _qlock:
        if not _queue:
            return None
        tid = _queue[0]
    t = conversations.get_turn(tid)
    if t is None or t["status"] != "queued":                    # deleted or already handled: drop the entry
        with _qlock:
            if _queue and _queue[0] == tid:
                _queue.popleft()
        return tid
    done = _generate_turn(tid, t["standalone_query"] or t["question"], t["retrieval"], llm=llm,
                          timeout=config.RAG_HEAVY_WAIT_S)
    if not done:
        return None
    with _qlock:
        if _queue and _queue[0] == tid:
            _queue.popleft()
    return tid


def _loop() -> None:
    while not _stop.is_set():
        _wake.wait(POLL_S)
        _wake.clear()
        while not _stop.is_set():
            try:
                if process_one() is None:
                    break
            except Exception as e:  # noqa: BLE001 — one bad item must not stop the worker
                print(f"[answers] queue item failed: {type(e).__name__}: {e}", file=sys.stderr)
                with _qlock:
                    if _queue:
                        tid = _queue.popleft()
                        try:
                            conversations.update_turn(tid, status="error", error=f"worker: {type(e).__name__}: {e}")
                        except Exception:  # noqa: BLE001
                            pass
                break


def start() -> int:
    """Backend startup: expire queued turns of a previous process, start the generation worker."""
    global _thread
    n = conversations.expire_queued()
    _stop.clear()
    if _thread is None or not _thread.is_alive():
        _thread = threading.Thread(target=_loop, name="reel-answers", daemon=True)
        _thread.start()
    return n


def stop() -> None:
    _stop.set()
    _wake.set()
    if _thread is not None:
        _thread.join(timeout=60)


# ---------------------------------------------------------------- response shape (API contract)

def response(t: dict) -> dict:
    r = t.get("retrieval") or {}
    a = t.get("answer")
    status = t["status"]
    if a is not None:
        ans = {k: a.get(k) for k in ("status", "text", "sentences", "removed", "missing", "conflict", "partial",
                                      "model_said_insufficient", "error")}
    else:
        ans = {"status": {"queued": "deferred", "retrieval_only": "unavailable", "retrieved": "unavailable"}
               .get(status, status), "text": None, "sentences": [], "removed": [], "reason": t.get("error")}
    return {
        "conversation_id": t["conversation_id"], "turn_id": t["id"], "request_id": t["id"],
        "question": t["question"], "standalone_query": t.get("standalone_query"),
        "rewrite": t.get("rewrite"), "mode_requested": t.get("mode_requested"), "mode_used": t.get("mode_used"),
        "fallback": r.get("fallback", []), "status": status, "answer": ans,
        "citations": (a or {}).get("citations", []),
        # Phase 5 (additive): concepts of the exact cited chunks, so the workspace can highlight them in the graph.
        "cited_concepts": [{"key": c.get("key"), "name": c.get("name")} for c in (t.get("cited_concepts") or [])],
        "sources": r.get("sources", []), "intent": r.get("intent"),
        "concepts": r.get("concepts", []), "connections": r.get("connections", {}),
        "timing": {"retrieval": r.get("timing", {}), "rewrite_s": (t.get("rewrite") or {}).get("rewrite_s"),
                   "generation": (a or {}).get("timing")},
    }


def request_status(tid: int) -> dict | None:
    t = conversations.get_turn(tid)
    return response(t) if t else None
