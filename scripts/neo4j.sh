#!/usr/bin/env bash
# Project-local Neo4j Community (GPLv3) for the Phase 4 knowledge graph. No sudo, nothing system-wide.
#   scripts/neo4j.sh install   download + sha256-verify into .tools/neo4j, write config, first-time credentials
#   scripts/neo4j.sh [status]|start|stop|restart|console
# Binary: .tools/neo4j   Config: .tools/neo4j-conf   Data/logs: output/neo4j (derived, rebuildable from SQLite)
# Listens on 127.0.0.1 only, on non-default ports (bolt 7697, http 7484) so it cannot clash with other projects.
#
# Credentials (.env.local, mode 600) are created ONCE, before the database is initialized, and never regenerated:
#   db not initialized, no credentials     → generate password, write .env.local, then set it as initial password
#   db not initialized, credentials exist  → reuse them (e.g. a previous install was interrupted)
#   db initialized,     credentials exist  → nothing to do
#   db initialized,     credentials absent → stop with instructions (never overwrite; data would be inaccessible)
#   credentials partially present          → stop and name the missing keys
# Paths can be overridden (NEO4J_HOME_DIR, NEO4J_CONF_DIR, NEO4J_DATA_DIR, NEO4J_ENV_FILE) — used by the tests.
set -euo pipefail

CMD="${1:-status}"
VERSION="${NEO4J_VERSION:-2026.10.2}"
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
HOME_DIR="${NEO4J_HOME_DIR:-$ROOT/.tools/neo4j}"
CONF_DIR="${NEO4J_CONF_DIR:-$ROOT/.tools/neo4j-conf}"
DATA_DIR="${NEO4J_DATA_DIR:-$ROOT/output/neo4j}"
ENV_FILE="${NEO4J_ENV_FILE:-$ROOT/.env.local}"
BOLT_PORT="${NEO4J_BOLT_PORT:-7697}"
HTTP_PORT="${NEO4J_HTTP_PORT:-7484}"
KEYS=(NEO4J_URI NEO4J_USER NEO4J_PASSWORD)

die() { echo "error: $*" >&2; exit 1; }

java_home() {
  if [[ -n "${JAVA_HOME:-}" ]]; then echo "$JAVA_HOME"; return; fi
  /usr/libexec/java_home -v 25 2>/dev/null || /usr/libexec/java_home -v 21 2>/dev/null || die "Java 21 or 25 required"
}

gen_password() {   # 32 hex chars from the OS CSPRNG; no pipeline, so no SIGPIPE under pipefail
  local pw
  pw="$(openssl rand -hex 16)"
  [[ "$pw" =~ ^[0-9a-f]{32}$ ]] || die "password generation failed"
  printf '%s' "$pw"
}

env_value() {      # env_value KEY → value from ENV_FILE (empty if absent)
  [[ -f "$ENV_FILE" ]] || return 0
  local line
  line="$(grep -E "^$1=" "$ENV_FILE" | tail -n 1 || true)"
  printf '%s' "${line#*=}"
}

db_initialized() { [[ -f "$DATA_DIR/data/dbms/auth.ini" || -n "$(ls -A "$DATA_DIR/data/databases" 2>/dev/null)" ]]; }

download() {
  local tgz="$ROOT/.tools/neo4j-community-$VERSION-unix.tar.gz"
  local url="https://dist.neo4j.org/neo4j-community-$VERSION-unix.tar.gz"
  mkdir -p "$ROOT/.tools"
  local expected
  expected="$(curl -fsSL --retry 3 "$url.sha256" | awk '{print $1}')" || die "checksum unavailable for $VERSION ($url.sha256); not installing"
  [[ "$expected" =~ ^[0-9a-f]{64}$ ]] || die "malformed checksum for $VERSION; not installing"
  echo "downloading $url"
  curl -fL --retry 3 -o "$tgz" "$url" || { rm -f "$tgz"; die "download failed"; }
  local actual
  actual="$(shasum -a 256 "$tgz" | awk '{print $1}')"
  if [[ "$expected" != "$actual" ]]; then rm -f "$tgz"; die "sha256 mismatch ($actual ≠ $expected)"; fi
  local tmp
  tmp="$(mktemp -d "$ROOT/.tools/neo4j-unpack.XXXX")"
  tar -xzf "$tgz" -C "$tmp"
  mv "$tmp"/neo4j-community-* "$HOME_DIR"
  rm -rf "$tmp" "$tgz"
  echo "installed Neo4j $VERSION → $HOME_DIR (sha256 verified)"
}

write_conf() {
  mkdir -p "$CONF_DIR" "$DATA_DIR"/{data,logs,run,import,plugins}
  cat > "$CONF_DIR/neo4j.conf" <<EOF
# Generated by scripts/neo4j.sh — local-only Neo4j for Reel Knowledge
server.default_listen_address=127.0.0.1
server.default_advertised_address=127.0.0.1
server.bolt.listen_address=127.0.0.1:$BOLT_PORT
server.bolt.advertised_address=127.0.0.1:$BOLT_PORT
server.http.listen_address=127.0.0.1:$HTTP_PORT
server.http.advertised_address=127.0.0.1:$HTTP_PORT
server.https.enabled=false
server.directories.data=$DATA_DIR/data
server.directories.logs=$DATA_DIR/logs
server.directories.run=$DATA_DIR/run
server.directories.import=$DATA_DIR/import
server.directories.plugins=$DATA_DIR/plugins
server.memory.heap.initial_size=512m
server.memory.heap.max_size=1g
server.memory.pagecache.size=512m
dbms.security.auth_enabled=true
dbms.usage_report.enabled=false
EOF
}

write_credentials() {  # append the 3 keys atomically (temp file + mv), preserving other lines; mode 600
  local pw="$1" tmp
  tmp="$(mktemp "$ENV_FILE.tmp.XXXX")"
  chmod 600 "$tmp"
  [[ -f "$ENV_FILE" ]] && cat "$ENV_FILE" > "$tmp"
  { echo "NEO4J_URI=bolt://127.0.0.1:$BOLT_PORT"; echo "NEO4J_USER=neo4j"; echo "NEO4J_PASSWORD=$pw"; } >> "$tmp"
  mv "$tmp" "$ENV_FILE"
  chmod 600 "$ENV_FILE"
}

init_credentials() {
  local present=() missing=() k
  for k in "${KEYS[@]}"; do
    if [[ -n "$(env_value "$k")" ]]; then present+=("$k"); else missing+=("$k"); fi
  done
  if (( ${#present[@]} > 0 && ${#missing[@]} > 0 )); then
    die "$ENV_FILE is incomplete (missing: ${missing[*]}); add them by hand — refusing to modify it"
  fi
  if db_initialized; then
    if (( ${#missing[@]} > 0 )); then
      die "the Neo4j database in $DATA_DIR is already initialized, but $ENV_FILE has no credentials.
       Restore NEO4J_URI/NEO4J_USER/NEO4J_PASSWORD there, or (derived data only) delete $DATA_DIR and re-run install."
    fi
    echo "credentials present; database already initialized (unchanged)"
    return
  fi
  local pw
  if (( ${#missing[@]} == 0 )); then
    pw="$(env_value NEO4J_PASSWORD)"
    echo "reusing existing credentials from $ENV_FILE for first-time initialization"
  else
    pw="$(gen_password)"
    write_credentials "$pw"               # persisted BEFORE use: an interrupted install retries with the same one
    echo "generated credentials → $ENV_FILE (mode 600)"
  fi
  JAVA_HOME="$(java_home)" NEO4J_CONF="$CONF_DIR" "$HOME_DIR/bin/neo4j-admin" dbms set-initial-password "$pw" >/dev/null
  echo "initial password set"
}

case "$CMD" in
  install)
    [[ -x "$HOME_DIR/bin/neo4j" ]] || download
    write_conf
    init_credentials
    ;;
  start|stop|status|console|restart)
    [[ -x "$HOME_DIR/bin/neo4j" ]] || die "not installed: run scripts/neo4j.sh install"
    JAVA_HOME="$(java_home)" NEO4J_CONF="$CONF_DIR" "$HOME_DIR/bin/neo4j" "$CMD"
    ;;
  *) die "usage: $0 install|start|stop|restart|status|console" ;;
esac